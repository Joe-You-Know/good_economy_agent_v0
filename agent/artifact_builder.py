import json
from pathlib import Path
from typing import Dict, List, Tuple

from .models import ArtifactRecord, Opportunity


class ArtifactBuilder:
    def __init__(self, output_dir: Path, license_text: str, support_links: Dict[str, str] = None):
        self.output_dir = Path(output_dir)
        self.public_dir = self.output_dir / "public_artifact"
        self.public_dir.mkdir(parents=True, exist_ok=True)
        self.license_text = license_text
        self.support_links = dict(support_links or {})

    def build(self, opportunity: Opportunity, ai_draft: str = None) -> ArtifactRecord:
        title, filename, claim, body, limitations = self._artifact_spec(opportunity)
        path = self.public_dir / filename
        revenue_path = self._revenue_path()
        content_source = "deterministic"

        if ai_draft:
            content_source = "openai_assisted_with_deterministic_guardrails"
            body = (
                body
                + "\n\n## Supplemental Draft Notes\n\n"
                + "The following notes were generated by the optional model-assisted mode and "
                + "should be reviewed before external publication.\n\n"
                + ai_draft.strip()
                + "\n"
            )

        path.write_text(self._render_artifact(title, body, limitations, revenue_path), encoding="utf-8")
        readme_path = self._write_bundle_readme(title, path.name, claim, revenue_path, limitations)
        revenue_path_file = self._write_revenue_path(revenue_path)
        manifest_path = self._write_manifest(opportunity, title, path, claim, revenue_path, limitations, content_source)

        files = [str(path), str(readme_path), str(revenue_path_file), str(manifest_path)]
        return ArtifactRecord(
            artifact_id=opportunity.id,
            title=title,
            category=opportunity.category,
            path=str(path),
            files=files,
            public_benefit_claim=claim,
            revenue_path=revenue_path,
            license=self.license_text,
            limitations=limitations,
            support_links=self.support_links,
            content_source=content_source,
            negative_ethics_debt=0.0,
            positive_ethics_score=opportunity.public_benefit_score,
        )

    def _artifact_spec(self, opportunity: Opportunity) -> Tuple[str, str, str, str, List[str]]:
        if opportunity.id == "accessibility_checklist":
            return self._accessibility_checklist()
        if opportunity.id == "resource_efficiency_template":
            return self._resource_efficiency_template()
        return self._education_artifact()

    def _accessibility_checklist(self) -> Tuple[str, str, str, str, List[str]]:
        title = "Small Project Accessibility Starter Kit"
        filename = "accessibility_starter_kit.md"
        claim = "Helps small public-good projects improve access to digital information and services."
        limitations = [
            "This is an educational checklist, not a legal compliance certification.",
            "A qualified accessibility review is still needed for high-risk or regulated services.",
            "Users should test with real assistive technology and affected users when possible.",
        ]
        body = """## Who This Helps

Small nonprofits, school projects, mutual-aid groups, open-source maintainers,
and public-good teams that need a no-cost first pass before asking for expert help.

## Fast Triage

| Check | Pass Evidence | Fix If Missing |
|---|---|---|
| Images have meaningful alt text | Decorative images are empty-alt; informative images explain the point | Add concise alt text or move complex details into nearby text |
| Keyboard navigation works | Every interactive element can be reached, used, and exited by keyboard | Use native buttons/links and visible focus states |
| Headings are logical | One main heading, then nested section headings in order | Reorder heading levels without using headings only for size |
| Links describe destination | Link text makes sense out of context | Replace "click here" with the action or destination |
| Contrast is readable | Body text and controls remain readable in normal lighting | Increase contrast and do not rely on color alone |
| Forms are labeled | Inputs have visible labels and recoverable errors | Add labels, hints, and clear correction instructions |
| Files have alternatives | PDFs/downloads have HTML or plain-text alternatives | Publish the core information as accessible text |

## Ten-Minute Audit Method

1. Open the page or document as a first-time user.
2. Navigate using only the keyboard.
3. Turn images off or ignore them and ask whether the task still makes sense.
4. Read only headings and links to see whether the structure is understandable.
5. Try the most important form, download, or call to action.
6. Log each barrier as: issue, affected user, evidence, suggested fix, owner.
7. Fix the highest-impact barrier first.
8. Re-test the exact task after the fix.

## Issue Log Template

| Priority | Barrier | Affected User | Evidence | Fix | Status |
|---|---|---|---|---|---|
| High |  |  |  |  |  |
| Medium |  |  |  |  |  |
| Low |  |  |  |  |  |

## Adaptive Agency Benefit

Accessibility preserves a person's ability to perceive truthful information,
make choices, recover from errors, and participate without avoidable dependency
on another person.
"""
        return title, filename, claim, body, limitations

    def _resource_efficiency_template(self) -> Tuple[str, str, str, str, List[str]]:
        title = "Pantry and Resource Efficiency Tracker"
        filename = "pantry_resource_efficiency_tracker.md"
        claim = "Helps households and small community groups reduce waste and plan around real inventory."
        limitations = [
            "This is a planning aid, not nutrition, medical, or food-safety advice.",
            "Users should follow local food-safety guidance and discard unsafe items.",
            "Donation rules vary by location and recipient organization.",
        ]
        body = """## Use Case

This tracker is for households, churches, schools, food shelves, and small
nonprofits that need a simple way to see what they already have before buying,
discarding, or requesting more.

## Inventory Table

| Item | Quantity | Use-By Date | Storage Location | Planned Use | Share/Donate By | Status |
|---|---:|---|---|---|---|---|
|  |  |  |  |  |  |  |

## Weekly Method

1. List food and supplies already available.
2. Sort by closest use-by date.
3. Plan meals or distributions around items that expire soon.
4. Mark surplus items that can be shared while still useful.
5. Record waste reason: expired, forgotten, duplicate purchase, storage issue.
6. Change next week's buying or request list based on actual waste.

## Waste Review

| Item Wasted | Amount | Reason | Preventive Change |
|---|---:|---|---|
|  |  |  |  |

## Adaptive Agency Benefit

Resource visibility helps people make better decisions under uncertainty,
stretch limited budgets, and reduce avoidable waste.
"""
        return title, filename, claim, body, limitations

    def _education_artifact(self) -> Tuple[str, str, str, str, List[str]]:
        title = "Adaptive Learning Worksheet Method"
        filename = "adaptive_learning_worksheet_method.md"
        claim = "Helps educators create worksheets that build durable learner capability."
        limitations = [
            "This is a general education template, not a substitute for a teacher's judgment.",
            "Examples should be checked for age, language, and accessibility fit.",
            "Learner data should not be collected without consent and a clear purpose.",
        ]
        body = """## Design Goal

The worksheet should help a learner observe, choose, try, receive feedback, and
adapt. It should not only ask the learner to repeat an answer pattern.

## Worksheet Structure

1. Concept in plain language.
2. One worked example.
3. Two guided practice questions.
4. Five independent practice questions.
5. One reflection question about what changed in the learner's thinking.

## Reusable Template

### Topic

[Write the topic.]

### Plain-Language Explanation

[Explain the concept in simple terms.]

### Worked Example

[Show one solved example and name each step.]

### Guided Practice

[Give two partially guided problems.]

### Independent Practice

[Give five independent problems.]

### Reflection

[Ask: What did you try first, what changed, and what would you try next time?]

## Adaptive Agency Benefit

The learner practices noticing uncertainty, choosing a strategy, learning from
feedback, and improving the next attempt.
"""
        return title, filename, claim, body, limitations

    def _render_artifact(self, title: str, body: str, limitations: List[str], revenue_path: str) -> str:
        limitation_lines = "\n".join(f"- {item}" for item in limitations)
        return f"""# {title}

{body.strip()}

## Limits and Safety Notes

{limitation_lines}

## Revenue Path

{revenue_path}

## License

{self.license_text}
"""

    def _revenue_path(self) -> str:
        base = (
            "This artifact is free. Valid future revenue paths are voluntary donation, "
            "sponsorship, or opt-in paid customization requested by the recipient. "
            "No cold outreach, hidden fees, fake urgency, or unsupported claims are allowed."
        )
        if not self.support_links:
            return base + " No public support links were configured for this dry run."

        link_parts = [f"{label}: {url}" for label, url in sorted(self.support_links.items())]
        return base + " Configured public support links: " + "; ".join(link_parts) + "."

    def _write_bundle_readme(
        self,
        title: str,
        artifact_filename: str,
        claim: str,
        revenue_path: str,
        limitations: List[str],
    ) -> Path:
        path = self.public_dir / "README.md"
        limitation_lines = "\n".join(f"- {item}" for item in limitations)
        path.write_text(
            f"""# Public Artifact Bundle

Primary artifact: [{artifact_filename}]({artifact_filename})

## Public Benefit Claim

{claim}

## Limits

{limitation_lines}

## Revenue Path

{revenue_path}

## Publication Boundary

This bundle is safe for local review. External publication should still pass the
ethics gate, platform rules, and any relevant legal review.
""",
            encoding="utf-8",
        )
        return path

    def _write_revenue_path(self, revenue_path: str) -> Path:
        path = self.public_dir / "revenue_path.md"
        path.write_text(
            f"""# Revenue Path

{revenue_path}

## Valid Revenue Conditions

- The payer understands what is offered.
- Payment is voluntary and opt-in.
- The source is traceable.
- The amount is reported net of fees.
- The payment is not self-funded, collusive, fake, or bot-inflated.
- The action that caused payment is present in the audit ledger.
""",
            encoding="utf-8",
        )
        return path

    def _write_manifest(
        self,
        opportunity: Opportunity,
        title: str,
        artifact_path: Path,
        claim: str,
        revenue_path: str,
        limitations: List[str],
        content_source: str,
    ) -> Path:
        path = self.public_dir / "manifest.json"
        manifest = {
            "artifact_id": opportunity.id,
            "title": title,
            "category": opportunity.category,
            "primary_file": artifact_path.name,
            "public_benefit_claim": claim,
            "revenue_path": revenue_path,
            "license": self.license_text,
            "limitations": limitations,
            "support_links_configured": sorted(self.support_links.keys()),
            "content_source": content_source,
            "negative_ethics_debt": 0.0,
        }
        path.write_text(json.dumps(manifest, indent=2, sort_keys=True), encoding="utf-8")
        return path
